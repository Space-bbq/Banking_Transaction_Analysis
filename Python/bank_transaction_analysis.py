"""Visualization"""

import matplotlib.pyplot as plt

monthly = df.groupby(
    df['Transaction_Date'].dt.month
)['Amount'].sum()

plt.figure(figsize=(10, 5))
monthly.plot(marker='o')

plt.title('Monthly Transactions')
plt.xlabel('Month')
plt.ylabel('Transaction Amount')
plt.grid(True)

plt.show()

