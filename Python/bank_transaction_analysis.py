top.sort_values(ascending=False).head(10)

"""Monthly Trend"""

df['Transaction_Date']=pd.to_datetime(df['Transaction_Date'])

monthly=df.groupby(
df['Transaction_Date'].dt.month
)['Amount'].sum().reset_index()

monthly

print(df['Transaction_Date'].head(10))
